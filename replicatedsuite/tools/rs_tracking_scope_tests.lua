T('quick import scope target overwrite does not alter player channels',function()
 local h,S,F=Boot({noRenderer=true});for _,file in ipairs({'data/rs_skill_effects.lua','data/rs_combat_ability_catalog.lua','data/ids/rs_buff_ids.lua','data/rs_status_tracking_catalog.lua'}) do dofile(file) end;dofile('features/combat/buff_display/rs_buff_display_transfer_v2.lua')
 assert(F:SetTrackedChannel(99,'player','buff',true));assert(F:SetTrackedChannel(88,'target','buff',true))
 local ok,err=F:ImportTrackedIds('21','buff','overwrite','target');assert(ok,err)
 assert(F:IsTrackedChannel(99,'player','buff'),'player changed by target overwrite')
 assert(F:IsTrackedChannel(21,'target','buff') and not F:IsTrackedChannel(88,'target','buff'),'target overwrite incorrect')
end)
